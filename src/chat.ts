/** All six languages, one per line (used when the user's language is unknown or not supported). */
export function messages(product: string): Record<Kind, string> {
  const t = texts(product);
  const all = (k: Kind) => SUPPORTED_LANGS.map((l) => t[k][l]).join("\n");
  return { declined: all("declined"), invalid: all("invalid"), busy: all("busy"), unavailable: all("unavailable"), retry: all("retry"), languages: all("languages") };
}

/** One line in the user's language when we are sure of it, otherwise all six. */
export function messageFor(product: string, kind: Kind, lang: Detected): string {
  return lang === "other" || lang === "unknown" ? messages(product)[kind] : texts(product)[kind][lang];
}

/**
 * What is safe to log about a failed model call: the error class and HTTP status.
 * Never the error message (it can echo request content), except for our own
 * EmptyReplyError whose text we wrote.
 */
function errInfo(e: unknown): Record<string, string | number> {
  const out: Record<string, string | number> = {};
  if (e instanceof Error) {
    out.error = e.name;
    const status = (e as { status?: unknown }).status;
    if (typeof status === "number") out.status = status;
    if (e.name === "EmptyReplyError") out.detail = e.message;
  }
  return out;
}

export async function handleChat(
  deps: ChatDeps,
  req: { sessionId: unknown; message: unknown; clientKey: string },
): Promise<ChatResponse> {
  const product = deps.config.productName;
  const msg = messages(product);

  // 1. Per-IP limit first: cheapest check. It also counts invalid requests, so a client cannot
  //    flood us with junk for free.
  if (!deps.limiter.allow(req.clientKey)) {
    deps.log("rate_limited");
    return { status: 429, body: { reply: msg.busy, blocked: true } };
  }

  // 2. Input validation and Unicode clean-up. Invalid input costs nothing and is refused before it
  //    can use up any daily cap.
  const input = normalizeInput(req.message, deps.config.maxInputChars);
  if (!input.ok) {
    deps.log("invalid_input", { reason: input.reason });
    return { status: 400, body: { reply: msg.invalid, blocked: true } };
  }
  const lang = detectLanguage(input.text);

  // 3. Daily caps, per client first so one client cannot use up the global cap for everybody.
  if (!deps.clientDaily.allow(req.clientKey)) {
    deps.log("client_daily_cap_reached");
    return { status: 429, body: { reply: messageFor(product, "busy", lang), blocked: true } };
  }
  if (!deps.daily.allow()) {
    deps.log("daily_cap_reached");
    return { status: 503, body: { reply: messageFor(product, "unavailable", lang), blocked: true } };
  }

  const sessionId = deps.sessions.open(req.sessionId);
  // When this message is too short or too mixed to detect, the conversation's language so far is the best guess
  // for fixed messages and for the hint. It is never used to override a language the detector is sure about.
  const sticky = deps.sessions.language(sessionId);
  const shown: Detected = lang === "unknown" && sticky ? sticky : lang;

  // 4. Injection classifier. Fails closed: if it cannot answer, nothing goes on. It also sees the
  //    user's earlier messages, so a set-up in one turn and a trigger in the next is visible to it.
  const earlier = deps.sessions.userMessages(sessionId, 3);
  let verdict;
  try {
    verdict = await deps.llm.classify(input.text, earlier.length > 0 ? earlier : undefined);
  } catch (e) {
    deps.log("classifier_error", errInfo(e));
    return { status: 503, body: { sessionId, reply: messageFor(product, "unavailable", shown), blocked: true } };
  }
  if (verdict !== "SAFE") {
    deps.log("blocked_by_classifier");
    // The blocked message is NOT stored, so it cannot poison later turns.
    return { status: 200, body: { sessionId, reply: messageFor(product, "declined", shown), blocked: true } };
  }

  // 5. Main model, with server-held history plus this message and a server-made language hint.
  const system = deps.systemPrompt + languageHint(lang, sticky);
  const turns = [...deps.sessions.history(sessionId), { role: "user" as const, content: input.text }];
  let result;
  try {
    result = await deps.llm.reply(system, turns);
  } catch (e) {
    deps.log("model_error", errInfo(e));
    return { status: 503, body: { sessionId, reply: messageFor(product, "unavailable", shown), blocked: true } };
  }
  if (result.kind === "refusal") {
    deps.log("model_refusal");
    return { status: 200, body: { sessionId, reply: messageFor(product, "declined", shown), blocked: true } };
  }

  // 6. Output guard.
  let checked = deps.outputGuard.check(result.text);
  if (!checked.ok) {
    deps.log("blocked_by_output_guard", { reason: checked.reason });
    return { status: 200, body: { sessionId, reply: messageFor(product, "declined", shown), blocked: true } };
  }

  // 7. Language check on the reply. The model sometimes ignores the hint (for example it answers an Italian
  //    question in English). When the user's language is certain and the reply is clearly in another one of the six,
  //    ask once more; if that fails too the user gets a fixed message in their own language.
  const expected = replyLanguages(lang, input.text);
  if (expected.length > 0 && wrongLanguage(result.text, expected)) {
    deps.log("language_retry");
    try {
      result = await deps.llm.reply(system + retryNote(expected), turns);
    } catch (e) {
      deps.log("model_error", errInfo(e));
      return { status: 503, body: { sessionId, reply: messageFor(product, "unavailable", shown), blocked: true } };
    }
    if (result.kind === "refusal") {
      deps.log("model_refusal");
      return { status: 200, body: { sessionId, reply: messageFor(product, "declined", shown), blocked: true } };
    }
    checked = deps.outputGuard.check(result.text);
    if (!checked.ok) {
      deps.log("blocked_by_output_guard", { reason: checked.reason });
      return { status: 200, body: { sessionId, reply: messageFor(product, "declined", shown), blocked: true } };
    }
    if (wrongLanguage(result.text, expected)) {
      deps.log("language_mismatch");
      // One certain language: say it in that language. Several candidates: all six, as for any unknown language.
      const fixedLang: Detected = expected.length === 1 ? expected[0]! : "unknown";
      return { status: 200, body: { sessionId, reply: messageFor(product, "retry", fixedLang), blocked: true } };
    }
  }

  // 8. A list of languages must be exactly the six. A wrong one is replaced by the fixed list (not by another model call).
  let text = result.text;
  if (languageListProblem(text)) {
    deps.log("language_list_fixed");
    const inReply = detectLanguage(text);
    const listLang: Lang = SUPPORTED_LANGS.includes(lang as Lang)
      ? (lang as Lang)
      : SUPPORTED_LANGS.includes(shown as Lang)
        ? (shown as Lang)
        : SUPPORTED_LANGS.includes(inReply as Lang)
          ? (inReply as Lang)
          : "en";
    text = messageFor(product, "languages", listLang);
  }

  deps.sessions.append(sessionId, input.text, text);
  if (SUPPORTED_LANGS.includes(lang as Lang)) deps.sessions.setLanguage(sessionId, lang as Lang);
  return { status: 200, body: { sessionId, reply: text } };
}

/**
 * The language(s) a reply may be in. When the user's language is certain: that one (unsupported languages get
 * English). When the detector could not pick one: the candidates the message could be written in, or none if
 * there is no evidence (then nothing is enforced).
 */
function replyLanguages(lang: Detected, text: string): Lang[] {
  if (lang === "other") return ["en"];
  if (lang === "unknown") return candidateLanguages(text);
  return [lang];
}

/** True only when the reply is clearly written in one of the six that is not allowed. A reply we cannot classify passes. */
function wrongLanguage(text: string, allowed: Lang[]): boolean {
  const got = detectLanguage(text);
  return SUPPORTED_LANGS.includes(got as Lang) && !allowed.includes(got as Lang);
}
