import type { Config } from "./config.ts";
import type { LlmClient } from "./llm.ts";
import type { SessionStore } from "./sessions.ts";
import type { OutputGuard } from "./guards/output.ts";
import type { SlidingWindowLimiter, DailyCap } from "./guards/ratelimit.ts";
import { normalizeInput } from "./guards/input.ts";

export interface ChatDeps {
  config: Config;
  llm: LlmClient;
  sessions: SessionStore;
  outputGuard: OutputGuard;
  systemPrompt: string;
  limiter: SlidingWindowLimiter;
  daily: DailyCap;
  log: (event: string, details?: Record<string, string | number>) => void;
}

export interface ChatResponse {
  status: number;
  body: { sessionId?: string; reply: string; blocked?: boolean };
}

// Fixed messages in all six languages. They are never generated by a model, so
// an attacker cannot influence their text. The Italian lines were written by the
// assistant and have NOT been reviewed by a native speaker.
const six = (en: string, es: string, fr: string, pt: string, de: string, it: string): string =>
  [en, es, fr, pt, de, it].join("\n");

